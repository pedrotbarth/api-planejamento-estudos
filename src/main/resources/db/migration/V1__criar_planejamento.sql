CREATE TABLE estudantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL
);

CREATE TABLE disciplinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    estudante_id BIGINT NOT NULL REFERENCES estudantes (id)
);

CREATE TABLE atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(160) NOT NULL,
    tipo VARCHAR(16) NOT NULL CHECK (tipo IN ('TRABALHO', 'PROVA', 'EXERCICIO')),
    data_limite DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDENTE', 'CONCLUIDA')),
    disciplina_id BIGINT NOT NULL REFERENCES disciplinas (id)
);

CREATE INDEX idx_disciplinas_estudante ON disciplinas (estudante_id);
CREATE INDEX idx_atividades_disciplina ON atividades (disciplina_id);
